export const HUB_COUNT = HUBS.length;

// Built once and shared: the same seventeen hundred titles for every race.
let index = null;

function hubIndex() {
  if (index) return index;
  index = new Map();
  for (const hub of HUBS) {
    index.set(titleKey(hub), hub);
    for (const alias of REDIRECTS[hub] || []) index.set(titleKey(alias), hub);
  }
  return index;
}

/**
 * The titles closed for one race: every hub, plus every title that redirects
 * to one, keyed the way the rest of the game keys titles and mapped back to
 * the hub each one closes.
 *
 * A race's own two articles are never closed. Racing *to* a hub is a perfectly
 * good race — it is routing *through* one that this mode is about — and a
 * target nobody can arrive at is not a race at all. The endpoints are passed
 * through resolved, so `USA -> United States` is excluded by the name the
 * board will actually see.
 *
 * @param {string} start resolved title
 * @param {string} target resolved title
 * @returns {Map<string,string>} title key -> the hub it belongs to
 */
export function closedFor(start, target) {
  const closed = new Map(hubIndex());
  for (const title of [start, target]) {
    if (!title) continue;
    // Both the article itself and every way of writing it: a race to United
    // States must not leave "U.S." closed on the board.
    const hub = closed.get(titleKey(title));
    if (!hub) continue;
    closed.delete(titleKey(hub));
    for (const alias of REDIRECTS[hub] || []) closed.delete(titleKey(alias));
  }
  return closed;
}
